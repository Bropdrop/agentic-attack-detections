#!/usr/bin/env python3
"""Build the WAF rules for Cloudflare, AWS WAF and Azure WAF from waf/signatures.yaml and iocs/indicators.csv.

    python3 tools/build_waf.py

Writes:
    waf/cloudflare/rules.json               custom rules for the Rulesets API (http_request_firewall_custom phase)
    waf/cloudflare/ip-list.json             items for a Cloudflare IP list named td_agentic_attack_ips
    waf/cloudflare/expressions.md           the same rules, ready to paste into the dashboard
    waf/cloudflare/terraform/main.tf        cloudflare_ruleset, cloudflare_list and its items (provider 5.x)
    waf/aws/rule-group.json                 `aws wafv2 create-rule-group --cli-input-json` input
    waf/aws/ip-set-ipv4.json, ip-set-ipv6.json   `aws wafv2 create-ip-set --cli-input-json` input
    waf/aws/cloudformation.yaml             rule group and IP sets in one stack
    waf/aws/terraform/main.tf               the same for Terraform (provider 5.x)
    waf/azure/appgw-custom-rules.json       Application Gateway WAF policy customRules, default actions
    waf/azure/appgw-policy.bicep, .json     Application Gateway WAF policy (Bicep and ARM)
    waf/azure/frontdoor-custom-rules.json   Front Door WAF policy customRules, default actions
    waf/azure/frontdoor-policy.bicep, .json Front Door WAF policy (Bicep and ARM)

Every output is deterministic, so CI can rebuild and compare. Needs PyYAML.
"""
import csv
import json
import re
from pathlib import Path
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parent.parent
WAF = ROOT / "waf"
HEADER = "Agentic attack detections by ThreatDefence. Generated by tools/build_waf.py from waf/signatures.yaml; do not edit."
TIERS = ("block", "challenge", "log", "opt-in")
CF_LIST = "td_agentic_attack_ips"
AWS_REGEX_MAX = 200          # characters per regex pattern (AWS WAF quota)
AZ_VALUES_MAX = 10           # string match values per Azure condition (Front Door limit; Application Gateway allows more)
AZ_IPS_MAX = 100             # addresses per Azure IPMatch condition, kept low so both services accept it
AZ_APPGW_MAX_PRIORITY = 100  # Application Gateway custom rule priorities run 1 to 100


def load():
    spec = yaml.safe_load((WAF / "signatures.yaml").read_text())
    ids = [g["id"] for g in spec["groups"]]
    assert len(ids) == len(set(ids)), "duplicate group id"
    for g in spec["groups"]:
        assert g["tier"] in TIERS, g["id"]
        for m in g["matchers"]:
            if m.get("nocase"):
                bad = [v for v in m["values"] if v != v.lower()]
                assert not bad, f"{g['id']}: nocase values must be lowercase: {bad}"
            if m.get("op") == "starts_with":
                assert not m.get("nocase"), f"{g['id']}: starts_with is case-sensitive on Cloudflare"
    return spec


def addresses(as_of):
    rows = list(csv.DictReader((ROOT / "iocs" / "indicators.csv").open(encoding="utf-8")))
    keep, dropped = [], []
    for r in rows:
        if r["type"] not in ("ipv4", "ipv6"):
            continue
        (dropped if r["review_by"] and r["review_by"] < as_of else keep).append(r)
    seen, out = set(), []
    for r in sorted(keep, key=lambda r: (r["type"], r["value"])):
        if r["value"] in seen:
            continue
        seen.add(r["value"])
        out.append({"ip": r["value"], "version": 4 if r["type"] == "ipv4" else 6,
                    "comment": f"{r['framework']} | {r['confidence']} | {r['source']} | review by {r['review_by']}"[:250]})
    return out, dropped


def camel(s):
    return "".join(p.capitalize() for p in re.split(r"[^a-zA-Z0-9]+", s) if p)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def dump_json(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def uri_variants(v):
    """The value plus its percent-encoded form, for platforms that cannot URL-decode before matching."""
    enc = quote(v, safe="/-_.~=&?%")
    return [v] if enc == v else [v, enc]


# ---------------------------------------------------------------- Cloudflare

CF_ACTIONS = {"block": "block", "challenge": "managed_challenge", "log": "log", "opt-in": "block"}


def cf_str(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cf_terms(m):
    f, op, nc = m["field"], m.get("op"), m.get("nocase", False)
    if f == "ip":
        return [f"ip.src in ${CF_LIST}"]
    if f == "header_name":
        return [f'any(lower(http.request.headers.names[*])[*] == {cf_str(v.lower())})' for v in m["values"]]
    if f == "authorization":
        return [f'any(http.request.headers["authorization"][*] contains {cf_str(v)})' for v in m["values"]]
    field = {"user_agent": "http.user_agent", "uri": "http.request.uri", "body": "http.request.body.raw"}[f]
    values = m["values"]
    if f == "uri":
        values = [x.lower() if nc else x for v in values for x in uri_variants(v)]
        values = list(dict.fromkeys(values))
    if op == "starts_with":
        return [f"starts_with({field}, {cf_str(v)})" for v in values]
    lhs = f"lower({field})" if nc else field
    return [f"{lhs} contains {cf_str(v)}" for v in values]


def cloudflare(spec, ips):
    rules = []
    for g in spec["groups"]:
        terms = [t for m in g["matchers"] for t in cf_terms(m)]
        enabled = g["tier"] in ("block", "challenge")
        if any(m["field"] == "body" for m in g["matchers"]):
            enabled = False  # http.request.body.raw needs Enterprise
        rules.append({
            "ref": "td_" + g["id"].replace("-", "_"),
            "description": f"TD {g['tier']}: {g['title']}",
            "expression": " or ".join(terms) if len(terms) < 2 else "(" + " or ".join(terms) + ")",
            "action": CF_ACTIONS[g["tier"]],
            "enabled": enabled,
        })
    write(WAF / "cloudflare" / "rules.json", dump_json(rules))
    write(WAF / "cloudflare" / "ip-list.json", dump_json([{"ip": a["ip"], "comment": a["comment"]} for a in ips]))

    md = [f"<!-- {HEADER} -->", "# Cloudflare custom rules", "",
          "Paste each expression into **Security > WAF > Custom rules > Create rule > Edit expression** and pick the action shown.",
          f"The address rule needs an IP list named `{CF_LIST}` first: **Manage Account > Configurations > Lists**, then import the addresses from `ip-list.json` (see the README).", "",
          "On the Free plan (5 custom rules) create the five rules marked *on by default*. The others need Enterprise (log action, body inspection) or only fit some sites.", ""]
    for r, g in zip(rules, spec["groups"]):
        md += [f"## {g['title']}", "",
               f"- Action: `{r['action']}`, " + ("on by default" if r["enabled"] else "off by default"),
               f"- Rule reference: `{r['ref']}`"]
        if g.get("note"):
            md.append(f"- {g['note']}")
        md += ["", "```", r["expression"], "```", ""]
    write(WAF / "cloudflare" / "expressions.md", "\n".join(md))

    tf = [f"# {HEADER}", "# Cloudflare provider 5.x. See waf/README.md.", "",
          'terraform {\n  required_providers {\n    cloudflare = {\n      source  = "cloudflare/cloudflare"\n      version = "~> 5.0"\n    }\n  }\n}', "",
          'variable "account_id" {\n  type = string\n}', "",
          'variable "zone_id" {\n  type = string\n}', "",
          'variable "enabled_refs" {\n  description = "Rule references to turn on. Defaults to the rules that are on by default."\n  type        = list(string)\n  default     = ' +
          json.dumps([r["ref"] for r in rules if r["enabled"]]) + "\n}", "",
          "locals {",
          "  td_addresses = " + json.dumps([a["ip"] for a in ips], indent=4).replace("\n]", "\n  ]") + "",
          "}", "",
          f'resource "cloudflare_list" "td_agentic_attack_ips" {{\n  account_id  = var.account_id\n  name        = "{CF_LIST}"\n  kind        = "ip"\n  description = "Agentic attack detections: reported addresses"\n}}', "",
          'resource "cloudflare_list_item" "td_agentic_attack_ips" {\n  for_each   = toset(local.td_addresses)\n  account_id = var.account_id\n  list_id    = cloudflare_list.td_agentic_attack_ips.id\n  ip         = each.value\n}', "",
          'resource "cloudflare_ruleset" "td_agentic_attack" {\n  zone_id = var.zone_id\n  name    = "Agentic attack detections"\n  kind    = "zone"\n  phase   = "http_request_firewall_custom"\n  rules = ['
          ]
    for r in rules:
        tf += ["    {",
               f"      ref         = {json.dumps(r['ref'])}",
               f"      description = {json.dumps(r['description'])}",
               f"      action      = {json.dumps(r['action'])}",
               f"      enabled     = contains(var.enabled_refs, {json.dumps(r['ref'])})",
               f"      expression  = {json.dumps(r['expression'])}",
               "    },"]
    tf += ["  ]", "", "  depends_on = [cloudflare_list_item.td_agentic_attack_ips]", "}", ""]
    write(WAF / "cloudflare" / "terraform" / "main.tf", "\n".join(tf).replace("${", "$${"))
    return rules


# ---------------------------------------------------------------- AWS WAF

AWS_FIELDS = {
    "user_agent": [{"SingleHeader": {"Name": "user-agent"}}],
    "authorization": [{"SingleHeader": {"Name": "authorization"}}],
    "uri": [{"UriPath": {}}, {"QueryString": {}}],
    "body": [{"Body": {"OversizeHandling": "CONTINUE"}}],
    "header_name": [{"Headers": {"MatchPattern": {"All": {}}, "MatchScope": "KEY", "OversizeHandling": "CONTINUE"}}],
}
IPV4_ARN = "${TD_AGENTIC_IPV4_SET_ARN}"
IPV6_ARN = "${TD_AGENTIC_IPV6_SET_ARN}"


def rx_escape(v):
    return re.sub(r"([.^$*+?()\[\]{}|\\])", r"\\\1", v)


def chunks(items, limit, size=len, sep=1):
    out, cur, n = [], [], 0
    for it in items:
        s = size(it)
        if cur and n + sep + s > limit:
            out.append(cur)
            cur, n = [], 0
        cur.append(it)
        n += s + (sep if len(cur) > 1 else 0)
    if cur:
        out.append(cur)
    return out


def aws_statements(m):
    f = m["field"]
    if f == "ip":
        return [{"IPSetReferenceStatement": {"ARN": IPV4_ARN}}, {"IPSetReferenceStatement": {"ARN": IPV6_ARN}}]
    values = [v for v in m["values"] if not (f == "uri" and "%" in v)]  # URL_DECODE makes encoded variants redundant
    alts = [("^" if m.get("op") == "starts_with" else "") + rx_escape(v.lower() if f == "header_name" else v) for v in values]
    # Header names are not anchored: the AWS documentation does not say whether keys are matched one by one or as one
    # joined string, and an unanchored name matches either way.
    tt = []
    if f == "uri":
        tt.append("URL_DECODE")
    if m.get("nocase") or f == "header_name":
        tt.append("LOWERCASE")
    tts = [{"Priority": i, "Type": t} for i, t in enumerate(tt)] or [{"Priority": 0, "Type": "NONE"}]
    out = []
    for ftm in AWS_FIELDS[f]:
        for part in chunks(alts, AWS_REGEX_MAX):
            rx = "|".join(part)  # top-level alternation only: AWS documents no support for grouping syntax
            out.append({"RegexMatchStatement": {"RegexString": rx,
                                                "FieldToMatch": ftm, "TextTransformations": tts}})
    return out


def aws_wcu(stmt):
    if "OrStatement" in stmt:
        return sum(aws_wcu(s) for s in stmt["OrStatement"]["Statements"])
    if "IPSetReferenceStatement" in stmt:
        return 1
    r = stmt["RegexMatchStatement"]
    return 3 + 10 * sum(1 for t in r["TextTransformations"] if t["Type"] != "NONE")


def aws_rules(spec, action_for):
    rules = []
    for prio, g in enumerate(spec["groups"]):
        st = [s for m in g["matchers"] for s in aws_statements(m)]
        stmt = st[0] if len(st) == 1 else {"OrStatement": {"Statements": st}}
        name = "td-" + g["id"]
        rules.append({"Name": name, "Priority": prio, "Statement": stmt, "Action": action_for(g),
                      "RuleLabels": [{"Name": f"td:agentic:{g['tier']}:{g['id']}"}],
                      "VisibilityConfig": {"SampledRequestsEnabled": True, "CloudWatchMetricsEnabled": True, "MetricName": name}})
    return rules


def aws(spec, ips):
    rules = aws_rules(spec, lambda g: {"Count": {}})
    wcu = sum(aws_wcu(r["Statement"]) for r in rules)
    capacity = max(100, -(-wcu * 3 // 2 // 50) * 50)  # 50% headroom: capacity cannot change after creation
    desc = "Agentic attack detections by ThreatDefence: framework fingerprints and reported addresses"
    vis = {"SampledRequestsEnabled": True, "CloudWatchMetricsEnabled": True, "MetricName": "td-agentic-attack"}
    group = {"Name": "td-agentic-attack", "Scope": "REGIONAL", "Capacity": capacity, "Description": desc,
             "Rules": rules, "VisibilityConfig": vis}
    write(WAF / "aws" / "rule-group.json", dump_json(group))
    sets = {}
    for v in (4, 6):
        sets[v] = {"Name": f"td-agentic-attack-ipv{v}", "Scope": "REGIONAL", "IPAddressVersion": f"IPV{v}",
                   "Description": f"Agentic attack detections: reported IPv{v} addresses",
                   "Addresses": [a["ip"] if "/" in a["ip"] else a["ip"] + ("/32" if v == 4 else "/128")
                                 for a in ips if a["version"] == v]}
        write(WAF / "aws" / f"ip-set-ipv{v}.json", dump_json(sets[v]))

    # CloudFormation
    def cfn_action(g):
        if g["tier"] == "block":
            return {"Fn::If": ["BlockTierBlocks", {"Block": {}}, {"Count": {}}]}
        if g["tier"] == "challenge":
            return {"Fn::If": ["ChallengeTierChallenges", {"Challenge": {}},
                               {"Fn::If": ["ChallengeTierCaptcha", {"Captcha": {}}, {"Count": {}}]}]}
        if g["tier"] == "opt-in":
            return {"Fn::If": ["OptInBlocks", {"Block": {}}, {"Count": {}}]}
        return {"Count": {}}

    cfn_rules = json.loads(json.dumps(aws_rules(spec, cfn_action))  # CloudFormation spells the key Arn
                           .replace('"ARN": ' + json.dumps(IPV4_ARN), '"Arn": ' + json.dumps({"Fn::GetAtt": ["IPv4Set", "Arn"]}))
                           .replace('"ARN": ' + json.dumps(IPV6_ARN), '"Arn": ' + json.dumps({"Fn::GetAtt": ["IPv6Set", "Arn"]})))
    cfn = {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": desc + ". " + HEADER,
        "Parameters": {
            "Scope": {"Type": "String", "Default": "REGIONAL", "AllowedValues": ["REGIONAL", "CLOUDFRONT"],
                      "Description": "CLOUDFRONT must be deployed in us-east-1"},
            "BlockTierAction": {"Type": "String", "Default": "Count", "AllowedValues": ["Count", "Block"],
                                "Description": "Action for the block-grade framework fingerprints"},
            "ChallengeTierAction": {"Type": "String", "Default": "Count", "AllowedValues": ["Count", "Challenge", "Captcha"],
                                    "Description": "Action for scanner user agents and reported addresses"},
            "OptInAction": {"Type": "String", "Default": "Count", "AllowedValues": ["Count", "Block"],
                            "Description": "Action for opt-in rules (WSUS services from the internet)"},
        },
        "Conditions": {
            "BlockTierBlocks": {"Fn::Equals": [{"Ref": "BlockTierAction"}, "Block"]},
            "ChallengeTierChallenges": {"Fn::Equals": [{"Ref": "ChallengeTierAction"}, "Challenge"]},
            "ChallengeTierCaptcha": {"Fn::Equals": [{"Ref": "ChallengeTierAction"}, "Captcha"]},
            "OptInBlocks": {"Fn::Equals": [{"Ref": "OptInAction"}, "Block"]},
        },
        "Resources": {
            **{f"IPv{v}Set": {"Type": "AWS::WAFv2::IPSet", "Properties": {
                "Name": sets[v]["Name"], "Scope": {"Ref": "Scope"}, "IPAddressVersion": sets[v]["IPAddressVersion"],
                "Description": sets[v]["Description"], "Addresses": sets[v]["Addresses"]}} for v in (4, 6)},
            "RuleGroup": {"Type": "AWS::WAFv2::RuleGroup", "Properties": {
                "Name": group["Name"], "Scope": {"Ref": "Scope"}, "Capacity": capacity, "Description": desc,
                "Rules": cfn_rules, "VisibilityConfig": vis}},
        },
        "Outputs": {"RuleGroupArn": {"Value": {"Fn::GetAtt": ["RuleGroup", "Arn"]}}},
    }
    write(WAF / "aws" / "cloudformation.yaml", f"# {HEADER}\n" + yaml.safe_dump(cfn, sort_keys=False, width=200))

    # Terraform
    tf = [f"# {HEADER}", "# AWS provider 5.x. See waf/README.md.", "",
          'terraform {\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 5.0"\n    }\n  }\n}', "",
          'variable "scope" {\n  description = "REGIONAL, or CLOUDFRONT (provider in us-east-1)"\n  type        = string\n  default     = "REGIONAL"\n}', "",
          'variable "block_tier_action" {\n  description = "count or block, for the block-grade framework fingerprints"\n  type        = string\n  default     = "count"\n}', "",
          'variable "challenge_tier_action" {\n  description = "count, challenge or captcha, for scanner user agents and reported addresses"\n  type        = string\n  default     = "count"\n}', "",
          'variable "opt_in_action" {\n  description = "count or block, for opt-in rules (WSUS services from the internet)"\n  type        = string\n  default     = "count"\n}', ""]
    for v in (4, 6):
        tf += [f'resource "aws_wafv2_ip_set" "td_ipv{v}" {{',
               f'  name               = "{sets[v]["Name"]}"', "  scope              = var.scope",
               f'  ip_address_version = "IPV{v}"', f'  description        = "{sets[v]["Description"]}"',
               "  addresses = " + json.dumps(sets[v]["Addresses"], indent=4).replace("\n]", "\n  ]"), "}", ""]
    tf += ['resource "aws_wafv2_rule_group" "td_agentic_attack" {', f'  name        = "{group["Name"]}"',
           "  scope       = var.scope", f"  capacity    = {capacity}", f"  description = {json.dumps(desc)}", ""]
    tier_var = {"block": "var.block_tier_action", "challenge": "var.challenge_tier_action", "opt-in": "var.opt_in_action"}
    for r, g in zip(rules, spec["groups"]):
        tf += ["  rule {", f'    name     = "{r["Name"]}"', f"    priority = {r['Priority']}", "", "    action {"]
        kinds = {"block": ["count", "block"], "challenge": ["count", "challenge", "captcha"], "opt-in": ["count", "block"]}.get(g["tier"])
        if kinds:
            for k in kinds:
                tf += [f'      dynamic "{k}" {{', f'        for_each = {tier_var[g["tier"]]} == "{k}" ? [1] : []',
                       "        content {}", "      }"]
        else:
            tf += ["      count {}"]
        tf += ["    }", ""]
        tf += hcl_block("statement", r["Statement"], 4)
        tf += ["", "    rule_label {", f'      name = "{r["RuleLabels"][0]["Name"]}"', "    }", "",
               "    visibility_config {", "      sampled_requests_enabled   = true",
               "      cloudwatch_metrics_enabled = true", f'      metric_name                = "{r["Name"]}"', "    }", "  }", ""]
    tf += ["  visibility_config {", "    sampled_requests_enabled   = true", "    cloudwatch_metrics_enabled = true",
           '    metric_name                = "td-agentic-attack"', "  }", "}", "",
           'output "rule_group_arn" {\n  value = aws_wafv2_rule_group.td_agentic_attack.arn\n}', ""]
    write(WAF / "aws" / "terraform" / "main.tf", "\n".join(tf))
    return group, wcu


def snake(k):
    special = {"IPSetReferenceStatement": "ip_set_reference_statement", "ARN": "arn", "OrStatement": "or_statement"}
    return special.get(k) or re.sub(r"(?<!^)(?=[A-Z])", "_", k).lower()


def hcl_block(name, obj, ind):
    pad = " " * ind
    lines = [f"{pad}{name} {{"]
    for k, v in obj.items():
        if k == "ARN":
            ref = "aws_wafv2_ip_set.td_ipv4.arn" if v == IPV4_ARN else "aws_wafv2_ip_set.td_ipv6.arn"
            lines.append(f"{pad}  arn = {ref}")
        elif k == "Statements":
            for s in v:
                lines += hcl_block("statement", s, ind + 2)
        elif k == "TextTransformations":
            for t in v:
                lines += [f"{pad}  text_transformation {{", f"{pad}    priority = {t['Priority']}", f'{pad}    type     = "{t["Type"]}"', f"{pad}  }}"]
        elif k == "MatchScope":
            lines.append(f'{pad}  match_scope = "{v}"')
        elif isinstance(v, dict):
            lines += hcl_block(snake(k), v, ind + 2)
        else:
            lines.append(f"{pad}  {snake(k)} = {json.dumps(v)}")
    if len(lines) == 1:
        return [f"{pad}{name} {{}}"]
    return lines + [f"{pad}}}"]


# ---------------------------------------------------------------- Azure WAF

def az_conditions(m, ips, frontdoor):
    """Yield (variable, selector, operator, values, transforms) for one matcher, split to fit Azure's limits."""
    f = m["field"]
    if f == "ip":
        addrs = [a["ip"] for a in ips if frontdoor or a["version"] == 4]  # Application Gateway IPMatch is IPv4 only
        for part in chunks(addrs, AZ_IPS_MAX, size=lambda _: 1, sep=0):
            yield ("RemoteAddr", None, "IPMatch", part, [])
        return
    regex = "RegEx" if frontdoor else "Regex"  # the two services spell the operator differently
    if f == "header_name":
        for v in m["values"]:
            yield ("RequestHeaders", v.upper() if v.startswith("x-") else v, regex, ["."], [])
        return
    var, sel = {"user_agent": ("RequestHeaders", "User-Agent"), "authorization": ("RequestHeaders", "Authorization"),
                "uri": ("RequestUri", None), "body": ("RequestBody", None)}[f]
    tf = (["UrlDecode"] if f == "uri" else []) + (["Lowercase"] if m.get("nocase") else [])
    op = "BeginsWith" if m.get("op") == "starts_with" else "Contains"
    # Application Gateway on CRS 3.1 and older rejects spaces and quotes in match values, so those become regular
    # expressions there. Front Door accepts them, and allows only 5 regex rules per policy, so it keeps plain values.
    values = [v for v in m["values"] if not (f == "uri" and "%" in v)]  # UrlDecode makes encoded variants redundant
    spaced = [] if frontdoor else [v for v in values if re.search(r"[\s'\"]", v)]
    plain = [v for v in values if v not in spaced]
    for part in chunks(plain, AZ_VALUES_MAX, size=lambda _: 1, sep=0):
        yield (var, sel, op, part, tf)
    rx = [("^" if op == "BeginsWith" else "") + rx_escape(v).replace(" ", r"\s") for v in spaced]
    for part in chunks(rx, AZ_VALUES_MAX, size=lambda _: 1, sep=0):
        yield (var, sel, regex, part, tf)


AZ_ACTION_PARAM = {"block": "blockAction", "challenge": "challengeAction", "opt-in": "optInAction"}
AZ_ACTION_DEFAULT = {"blockAction": "Block", "challengeAction": "Log", "optInAction": "Log"}


def az_rules(spec, ips, frontdoor):
    out = []
    for g in spec["groups"]:
        conds = [c for m in g["matchers"] for c in az_conditions(m, ips, frontdoor)]
        for i, (var, sel, op, values, tf) in enumerate(conds, 1):
            name = "Td" + camel(g["id"]) + (str(i) if len(conds) > 1 else "")
            if frontdoor:
                mc = {"matchVariable": "RequestHeader" if var == "RequestHeaders" else var}
                if sel:
                    mc["selector"] = sel
                mc.update({"operator": op, "negateCondition": False, "matchValue": values, "transforms": tf})
            else:
                mv = {"variableName": var}
                if sel:
                    mv["selector"] = sel
                mc = {"matchVariables": [mv], "operator": op, "matchValues": values, "transforms": tf}
            out.append({"group": g["id"], "tier": g["tier"], "name": name, "matchConditions": [mc]})
    return out


class Raw(str):
    """A Bicep expression, written without quotes."""


def bicep_value(v, ind):
    pad = "  " * ind
    if isinstance(v, Raw):
        return str(v)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'").replace("${", "\\${") + "'"
    if isinstance(v, list):
        if not v:
            return "[]"
        return "[\n" + "".join(f"{pad}  {bicep_value(x, ind + 1)}\n" for x in v) + f"{pad}]"
    return "{\n" + "".join(f"{pad}  {k}: {bicep_value(x, ind + 1)}\n" for k, x in v.items()) + f"{pad}}}"


def azure(spec, ips):
    results = {}
    for frontdoor in (False, True):
        kind = "frontdoor" if frontdoor else "appgw"
        rules = az_rules(spec, ips, frontdoor)
        n = len(rules)
        base_default = max(1, min(50, AZ_APPGW_MAX_PRIORITY - n)) if not frontdoor else 100
        concrete, arm_rules, bicep_rules = [], [], []
        for i, r in enumerate(rules):
            param = AZ_ACTION_PARAM.get(r["tier"])
            state_key = "enabledState" if frontdoor else "state"
            common = {"name": r["name"], "ruleType": "MatchRule", state_key: "Enabled", "matchConditions": r["matchConditions"]}
            concrete.append({**common, "priority": base_default + i, "action": AZ_ACTION_DEFAULT[param] if param else "Log"})
            arm_rules.append({**common, "priority": f"[add(parameters('basePriority'), {i})]",
                              "action": f"[parameters('{param}')]" if param else "Log"})
            bicep_rules.append({**common, "priority": Raw(f"basePriority + {i}"), "action": Raw(param) if param else "Log"})
        write(WAF / "azure" / f"{kind}-custom-rules.json", dump_json(concrete))

        actions = {"Block", "Log"}
        params_doc = {
            "policyName": ("string", "TdAgenticAttack", None, "Name of the WAF policy to create"),
            "mode": ("string", "Detection", ["Detection", "Prevention"], "Detection logs every match; Prevention enforces Block actions"),
            "blockAction": ("string", "Block", sorted(actions), "Action for block-grade framework fingerprints"),
            "challengeAction": ("string", "Log", sorted(actions), "Action for scanner user agents and reported addresses"),
            "optInAction": ("string", "Log", sorted(actions), "Action for opt-in rules (WSUS services from the internet)"),
            "basePriority": ("int", base_default, None, f"Priority of the first rule; the {n} rules take the next {n - 1} numbers" +
                             ("" if frontdoor else ". Application Gateway priorities run 1 to 100")),
        }
        if frontdoor:
            params_doc["sku"] = ("string", "Premium_AzureFrontDoor", ["Premium_AzureFrontDoor", "Standard_AzureFrontDoor"], "Front Door tier")
        else:
            params_doc["location"] = ("string", "[resourceGroup().location]", None, "Region of the Application Gateway")

        if frontdoor:
            props = {"policySettings": {"enabledState": "Enabled", "mode": "[parameters('mode')]"},
                     "customRules": {"rules": arm_rules}}
            res = {"type": "Microsoft.Network/FrontDoorWebApplicationFirewallPolicies", "apiVersion": "2024-02-01",
                   "name": "[parameters('policyName')]", "location": "Global", "sku": {"name": "[parameters('sku')]"}, "properties": props}
            bprops = {"policySettings": {"enabledState": "Enabled", "mode": Raw("mode")}, "customRules": {"rules": bicep_rules}}
            bres = ("resource policy 'Microsoft.Network/FrontDoorWebApplicationFirewallPolicies@2024-02-01' = ",
                    {"name": Raw("policyName"), "location": "Global", "sku": {"name": Raw("sku")}, "properties": bprops})
        else:
            managed = {"managedRuleSets": [{"ruleSetType": "Microsoft_DefaultRuleSet", "ruleSetVersion": "2.1"}]}
            props = {"policySettings": {"state": "Enabled", "mode": "[parameters('mode')]", "requestBodyCheck": True},
                     "customRules": arm_rules, "managedRules": managed}
            res = {"type": "Microsoft.Network/ApplicationGatewayWebApplicationFirewallPolicies", "apiVersion": "2024-05-01",
                   "name": "[parameters('policyName')]", "location": "[parameters('location')]", "properties": props}
            bprops = {"policySettings": {"state": "Enabled", "mode": Raw("mode"), "requestBodyCheck": True},
                      "customRules": bicep_rules, "managedRules": managed}
            bres = ("resource policy 'Microsoft.Network/ApplicationGatewayWebApplicationFirewallPolicies@2024-05-01' = ",
                    {"name": Raw("policyName"), "location": Raw("location"), "properties": bprops})

        arm = {"$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
               "contentVersion": "1.0.0.0", "metadata": {"description": HEADER}, "parameters": {}, "resources": [res],
               "outputs": {"policyId": {"type": "string", "value": f"[resourceId('{res['type']}', parameters('policyName'))]"}}}
        bicep = [f"// {HEADER}", ""]
        for k, (typ, default, allowed, d) in params_doc.items():
            arm["parameters"][k] = {"type": typ, "defaultValue": default, "metadata": {"description": d}}
            if allowed:
                arm["parameters"][k]["allowedValues"] = allowed
                bicep.append("@allowed([" + ", ".join(f"'{a}'" for a in allowed) + "])")
            bicep.append(f"@description('{d}')")
            dv = "resourceGroup().location" if default == "[resourceGroup().location]" else (str(default) if typ == "int" else f"'{default}'")
            bicep += [f"param {k} {typ} = {dv}", ""]
        bicep += [bres[0] + bicep_value(bres[1], 0), "", "output policyId string = policy.id", ""]
        write(WAF / "azure" / f"{kind}-policy.json", dump_json(arm))
        write(WAF / "azure" / f"{kind}-policy.bicep", "\n".join(bicep))
        results[kind] = n
    return results


